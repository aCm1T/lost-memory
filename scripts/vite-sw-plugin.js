/**
 * Vite plugin: emit a production service worker with hashed precache list.
 * Safe update strategy:
 * - HTML / navigations: network-first, cache fallback
 * - hashed assets: cache-first
 * - activate deletes old caches so updates are not bricked
 */
import { writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

function listFiles(dir, base = dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) listFiles(full, base, out);
    else out.push(relative(base, full).split('\\').join('/'));
  }
  return out;
}

export function lostMemoryServiceWorkerPlugin() {
  let outDir = 'dist';
  let base = '/lost-memory/';

  return {
    name: 'lost-memory-sw',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir;
      base = config.base.endsWith('/') ? config.base : `${config.base}/`;
    },
    closeBundle() {
      const files = listFiles(outDir).filter((file) => !file.endsWith('.map') && file !== 'sw.js');
      const version = `lost-memory-${Date.now().toString(36)}`;
      const precache = JSON.stringify(
        Array.from(new Set([base, `${base}index.html`, ...files.map((file) => `${base}${file}`)])),
      );

      const source = `/* Auto-generated by lost-memory-sw plugin. Do not edit. */
const CACHE_VERSION = ${JSON.stringify(version)};
const PRECACHE = ${precache};
const BASE = ${JSON.stringify(base)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE_VERSION)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting())
      .catch((error) => {
        console.warn('[sw] precache failed', error);
      }),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((key) => key !== CACHE_VERSION).map((key) => caches.delete(key))),
      )
      .then(() => self.clients.claim()),
  );
});

function isNavigationRequest(request) {
  return (
    request.mode === 'navigate' ||
    (request.method === 'GET' && request.headers.get('accept')?.includes('text/html'))
  );
}

function sameOrigin(url) {
  return url.origin === self.location.origin && url.pathname.startsWith(BASE);
}

async function networkFirst(request) {
  const cache = await caches.open(CACHE_VERSION);
  try {
    const fresh = await fetch(request);
    if (fresh && fresh.ok) {
      cache.put(request, fresh.clone());
    }
    return fresh;
  } catch (error) {
    const cached = await cache.match(request);
    if (cached) return cached;
    const fallback = await cache.match(BASE + 'index.html');
    if (fallback) return fallback;
    throw error;
  }
}

async function cacheFirst(request) {
  const cache = await caches.open(CACHE_VERSION);
  const cached = await cache.match(request);
  if (cached) return cached;
  const fresh = await fetch(request);
  if (fresh && fresh.ok) {
    cache.put(request, fresh.clone());
  }
  return fresh;
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (!sameOrigin(url)) return;

  if (isNavigationRequest(request) || url.pathname === BASE || url.pathname === BASE + 'index.html') {
    event.respondWith(networkFirst(request));
    return;
  }

  event.respondWith(cacheFirst(request));
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});
`;

      writeFileSync(join(outDir, 'sw.js'), source);
      console.log(`[lost-memory-sw] wrote sw.js (${files.length} files, ${version})`);
    },
  };
}
